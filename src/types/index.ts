// ── Core enumerations ──────────────────────────────────────────────────────

export type Priority = 'high' | 'medium' | 'low' | 'none';

export type Category = 'work' | 'personal' | 'project' | 'routine';

export type TaskStatus = 'todo' | 'in-progress' | 'done';

/** How far before the due date to fire a reminder notification */
export type ReminderOffset =
  | 'none'     // no reminder
  | 'at'       // at due time
  | '15'       // 15 min before
  | '30'       // 30 min before
  | '60'       // 1 hour before
  | '1440';    // 1 day before

/** Recurring task interval patterns */
export type RecurringPattern =
  | 'none'
  | 'daily'
  | 'weekdays'   // Mon–Fri
  | 'weekly'
  | 'monthly';

// ── Core task type ─────────────────────────────────────────────────────────

export interface Task {
  /** UUID, auto-generated by Dexie */
  id: string;

  /** The main task text (parsed shortcut tokens are stripped after parsing) */
  title: string;

  /** Optional longer description */
  description?: string;

  priority: Priority;
  category?: Category;
  status: TaskStatus;

  /** ISO date string (YYYY-MM-DD) or full ISO timestamp */
  dueDate?: string;

  /** Offset before dueDate to fire the push notification */
  reminderOffset: ReminderOffset;

  /** Recurring pattern */
  recurring: RecurringPattern;

  /** Tags extracted from #tag shortcut (lowercase, no #) */
  tags: string[];

  /** ISO timestamp when task was created */
  createdAt: string;

  /** ISO timestamp when task was last updated */
  updatedAt: string;

  /** ISO timestamp when task was completed (set when status → done) */
  completedAt?: string;

  /** When recurring, the id of the "parent" task this was generated from */
  recurringParentId?: string;
}

// ── Parsed shortcut tokens from the quick-add input ───────────────────────

export interface ParsedInput {
  /** Title with all shortcut tokens stripped */
  title: string;
  priority?: Priority;
  category?: Category;
  dueDate?: string;
  recurring?: RecurringPattern;
  tags: string[];
}

// ── UI state types ─────────────────────────────────────────────────────────

export type ViewId = 'today' | 'upcoming' | 'all' | 'dashboard' | 'settings';

export type SortBy = 'createdAt' | 'dueDate' | 'priority';
export type SortDir = 'asc' | 'desc';

export interface FilterState {
  priority?: Priority;
  category?: Category;
  tags: string[];
  search: string;
  sortBy: SortBy;
  sortDir: SortDir;
}

// ── Settings ───────────────────────────────────────────────────────────────

export interface AppSettings {
  theme: 'dark' | 'light' | 'system';
  /** Whether push notifications are enabled */
  notificationsEnabled: boolean;
  /** Default reminder offset for new tasks */
  defaultReminderOffset: ReminderOffset;
  /** Default priority for new tasks */
  defaultPriority: Priority;
  /** Show completed tasks in views */
  showCompleted: boolean;
}

export const DEFAULT_SETTINGS: AppSettings = {
  theme: 'dark',
  notificationsEnabled: false,
  defaultReminderOffset: '30',
  defaultPriority: 'none',
  showCompleted: false,
};
